#!/usr/bin/env node
// Generates RonisItemPedia/Data/ItemNames.lua: every item's name, quality and
// binding from the WoW Forever client's ItemSparse table, so the search box can
// find items the game has not cached yet.
//
// Usage:
//   node tools/gen_item_names.js <dir-with-csvs> <build> > Data/ItemNames.lua
// Needed tables: ItemSparse.
"use strict";
const fs = require("fs");
const path = require("path");

const [dir, build] = process.argv.slice(2);
if (!dir || !build) {
  console.error("usage: gen_item_names.js <csv-dir> <build>");
  process.exit(1);
}

function parseCSV(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else quoted = false;
      } else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field.replace(/\r$/, "")); rows.push(row); row = []; field = ""; }
    else field += c;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  const head = rows.shift();
  return rows.filter(r => r.length === head.length).map(r => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

const num = v => Number(v) || 0;
// Internal and placeholder items players never see.
const JUNK = /^(Monster - |OLD|TEST|Test |QA|DEPRECATED|Deprecated|zz|Unused|\[PH\])|\[PH\]|\bDEPRECATED\b|\(old\)|\(test\)/i;

const out = [];
for (const r of parseCSV(fs.readFileSync(path.join(dir, "ItemSparse.csv"), "utf8"))) {
  const name = (r.Display_lang || "").trim();
  if (!name || JUNK.test(name)) continue;
  out.push([num(r.ID), name, num(r.OverallQualityID), num(r.Bonding)]);
}
out.sort((a, b) => a[0] - b[0]);

const lua = s => '"' + s.replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';
const res = [];
res.push("-- GENERATED by tools/gen_item_names.js from the WoW Forever client DB2 tables");
res.push(`-- (build ${build}, CSV exports via wago.tools). Do not edit by hand.`);
res.push("-- Flat list, 4 values per item: itemID, name, quality, bonding");
res.push("-- (bonding: 0 none, 1 on pickup, 2 on equip, 3 on use, 4 quest item)");
res.push("local _, ns = ...");
res.push("ns.ITEM_DATA = {");
for (const [id, name, q, b] of out) res.push(`${id},${lua(name)},${q},${b},`);
res.push("}");
process.stdout.write(res.join("\n") + "\n");
console.error(`${out.length} items`);
