#!/usr/bin/env node
// Generates RonisItemPedia/Data/Recipes.lua from the WoW Forever client's own
// DB2 tables (CSV exports from https://wago.tools/db2/<Table>/csv?build=<build>).
//
// Usage:
//   node tools/gen_recipes.js <dir-with-csvs> <build> > Data/Recipes.lua
// Needed tables: SkillLineAbility, SpellReagents, SpellEffect, ItemEffect,
// ItemXItemEffect, ItemSparse.
"use strict";
const fs = require("fs");
const path = require("path");

const [dir, build] = process.argv.slice(2);
if (!dir || !build) {
  console.error("usage: gen_recipes.js <csv-dir> <build>");
  process.exit(1);
}

// Profession skill lines (Classic IDs) in display order.
const PROFS = [
  [171, "Alchemy"], [164, "Blacksmithing"], [185, "Cooking"], [333, "Enchanting"],
  [202, "Engineering"], [129, "First Aid"], [165, "Leatherworking"], [186, "Mining"],
  [197, "Tailoring"], [40, "Poisons"],
];
const PROF_INDEX = new Map(PROFS.map(([id], i) => [id, i + 1]));

const EFFECT_CREATE_ITEM = 24;
const EFFECT_ENCHANT_ITEM = 53;

function parseCSV(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else quoted = false;
      } else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field.replace(/\r$/, "")); rows.push(row); row = []; field = ""; }
    else field += c;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  const head = rows.shift();
  return rows.filter(r => r.length === head.length).map(r => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

const load = name => parseCSV(fs.readFileSync(path.join(dir, name + ".csv"), "utf8"));
const num = v => Number(v) || 0;

// Season of Discovery leftovers present in the client data but not in Forever.
const excluded = new Set(
  fs.readFileSync(path.join(__dirname, "sod_leftovers.txt"), "utf8")
    .split(/\r?\n/).filter(l => /^\d+$/.test(l.trim())).map(Number)
);

// spell -> { prof }
const abilities = new Map();
for (const r of load("SkillLineAbility")) {
  const prof = PROF_INDEX.get(num(r.SkillLine));
  if (!prof) continue;
  const spell = num(r.Spell);
  if (!excluded.has(spell) && !abilities.has(spell)) {
    abilities.set(spell, {
      prof,
      minRank: num(r.MinSkillLineRank),
      yellow: num(r.TrivialSkillLineRankLow),
      grey: num(r.TrivialSkillLineRankHigh),
      auto: num(r.AcquireMethod) === 1, // learned automatically with the skill
    });
  }
}

// spell -> recipe items that teach it (item effect trigger 6 = learn spell),
// with the skill rank the recipe item needs.
const itemEffects = new Map(load("ItemEffect").map(r => [r.ID, r]));
const sparse = new Map(load("ItemSparse").map(r => [num(r.ID), r]));
const teachers = new Map();
for (const x of load("ItemXItemEffect")) {
  const e = itemEffects.get(x.ItemEffectID);
  if (!e || num(e.TriggerType) !== 6) continue;
  const spell = num(e.SpellID), item = num(x.ItemID);
  if (!abilities.has(spell) || !sparse.has(item)) continue;
  if (!teachers.has(spell)) teachers.set(spell, []);
  if (!teachers.get(spell).includes(item)) teachers.get(spell).push(item);
}

// spell -> reagents [[item, count], ...]
const reagents = new Map();
for (const r of load("SpellReagents")) {
  const list = [];
  for (let i = 0; i < 8; i++) {
    const item = num(r["Reagent_" + i]), count = num(r["ReagentCount_" + i]);
    if (item > 0 && count > 0) list.push([item, count]);
  }
  if (list.length) reagents.set(num(r.SpellID), list);
}

// spell -> { item, min, max } (created item) or { enchant: true }
const products = new Map();
for (const r of load("SpellEffect")) {
  const spell = num(r.SpellID);
  if (!abilities.has(spell) || products.has(spell)) continue;
  const effect = num(r.Effect);
  if (effect === EFFECT_CREATE_ITEM && num(r.EffectItemType) > 0) {
    const base = Math.max(1, Math.round(num(r.EffectBasePointsF)));
    products.set(spell, { item: num(r.EffectItemType), min: base, max: base });
  } else if (effect === EFFECT_ENCHANT_ITEM) {
    products.set(spell, { enchant: true });
  }
}

const out = [];
for (const [spell, a] of abilities) {
  const reg = reagents.get(spell);
  const prod = products.get(spell);
  if (!reg || !prod) continue; // not a crafting recipe (gathering, passive, etc.)
  const items = (teachers.get(spell) || []).sort((x, y) => x - y);
  // skill needed to learn it: the recipe item's requirement, else the ability's own
  let learn = 0;
  for (const i of items) {
    const rank = num(sparse.get(i).RequiredSkillRank);
    if (rank > 0 && (learn === 0 || rank < learn)) learn = rank;
  }
  if (learn === 0 && a.minRank > 1) learn = a.minRank;
  out.push({ spell, ...a, prod, reg, learn, items });
}
out.sort((x, y) => x.prof - y.prof || x.spell - y.spell);

const lines = [];
lines.push("-- GENERATED by tools/gen_recipes.js from the WoW Forever client DB2 tables");
lines.push(`-- (build ${build}, CSV exports via wago.tools). Do not edit by hand.`);
lines.push("-- Each recipe: { spellID, professionIndex, productItemID (0 = enchant), madeMin, madeMax, { reagentID, count, ... },");
lines.push("--   learnSkill (0 = unknown), yellowSkill, greySkill, autoLearned (1/0), { recipeItemID, ... } }");
lines.push("local _, ns = ...");
lines.push(`ns.RECIPE_BUILD = "${build}"`);
lines.push("ns.RECIPE_PROFS = { " + PROFS.map(([, n]) => JSON.stringify(n)).join(", ") + " }");
lines.push("ns.RECIPES = {");
for (const r of out) {
  const p = r.prod.enchant ? [0, 1, 1] : [r.prod.item, r.prod.min, r.prod.max];
  lines.push(`  {${r.spell},${r.prof},${p.join(",")},{${r.reg.flat().join(",")}},${r.learn},${r.yellow},${r.grey},${r.auto ? 1 : 0},{${r.items.join(",")}}},`);
}
lines.push("}");
process.stdout.write(lines.join("\n") + "\n");
console.error(`${out.length} recipes`);
