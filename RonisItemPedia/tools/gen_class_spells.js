#!/usr/bin/env node
// Generates RonisItemPedia/Data/ClassSpells.lua: class spells that use an item
// as a reagent (Water Walking needs Fish Oil, Ritual of Summoning a Soul Shard...),
// from the WoW Forever client's DB2 tables (CSV exports from wago.tools).
//
// Usage:
//   node tools/gen_class_spells.js <dir-with-csvs> <build> > Data/ClassSpells.lua
// Needed tables: SkillLine, SkillLineAbility, SpellReagents.
"use strict";
const fs = require("fs");
const path = require("path");

const [dir, build] = process.argv.slice(2);
if (!dir || !build) {
  console.error("usage: gen_class_spells.js <csv-dir> <build>");
  process.exit(1);
}

function parseCSV(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else quoted = false;
      } else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field.replace(/\r$/, "")); rows.push(row); row = []; field = ""; }
    else field += c;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  const head = rows.shift();
  return rows.filter(r => r.length === head.length).map(r => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

const load = name => parseCSV(fs.readFileSync(path.join(dir, name + ".csv"), "utf8"));
const num = v => Number(v) || 0;

const excluded = new Set(
  fs.readFileSync(path.join(__dirname, "sod_leftovers.txt"), "utf8")
    .split(/\r?\n/).filter(l => /^\d+$/.test(l.trim())).map(Number)
);

const CLASS_CATEGORY = 7;
// Skill lines in the class category that are not real class spells here.
const SKIP_LINES = new Set(["Engraving", "Companions", "Mounts", "Pet - "]);
const CLASS_BITS = [
  [1, "WARRIOR"], [2, "PALADIN"], [4, "HUNTER"], [8, "ROGUE"], [16, "PRIEST"],
  [64, "SHAMAN"], [128, "MAGE"], [256, "WARLOCK"], [1024, "DRUID"],
];

const lines = new Map(load("SkillLine").map(r => [r.ID, r]));
const spells = new Map(); // spell -> Set(class)
for (const r of load("SkillLineAbility")) {
  const line = lines.get(r.SkillLine);
  if (!line || num(line.CategoryID) !== CLASS_CATEGORY) continue;
  const name = line.DisplayName_lang || "";
  if ([...SKIP_LINES].some(s => name.startsWith(s))) continue;
  const spell = num(r.Spell), mask = num(r.ClassMask);
  if (excluded.has(spell) || mask === 0) continue;
  if (!spells.has(spell)) spells.set(spell, new Set());
  for (const [bit, cls] of CLASS_BITS) if (mask & bit) spells.get(spell).add(cls);
}

const out = [];
for (const r of load("SpellReagents")) {
  const spell = num(r.SpellID);
  const classes = spells.get(spell);
  if (!classes || classes.size === 0) continue;
  const list = [];
  for (let i = 0; i < 8; i++) {
    const item = num(r["Reagent_" + i]), count = num(r["ReagentCount_" + i]);
    if (item > 0 && count > 0) list.push(item, count);
  }
  if (list.length) out.push({ spell, classes: [...classes].sort(), list });
}
out.sort((a, b) => a.spell - b.spell);

const res = [];
res.push("-- GENERATED by tools/gen_class_spells.js from the WoW Forever client DB2 tables");
res.push(`-- (build ${build}, CSV exports via wago.tools). Do not edit by hand.`);
res.push("-- Each entry: { spellID, \"CLASS1,CLASS2\", { reagentID, count, ... } }");
res.push("local _, ns = ...");
res.push("ns.CLASS_SPELLS = {");
for (const s of out) res.push(`  {${s.spell},"${s.classes.join(",")}",{${s.list.join(",")}}},`);
res.push("}");
process.stdout.write(res.join("\n") + "\n");
console.error(`${out.length} class spells with reagents`);
