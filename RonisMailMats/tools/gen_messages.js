#!/usr/bin/env node
// Generates RonisMailMats/Data/Messages.lua from tools/messages/*.json
// (arrays of { tone, text }; one file per model that wrote them).
//
// Usage: node tools/gen_messages.js > Data/Messages.lua
// Every message is checked: one line, at most 160 characters, no | \ or ",
// placeholders only {name} and {what}, no duplicates. Problems are fatal.
"use strict";
const fs = require("fs");
const path = require("path");

const dir = path.join(__dirname, "messages");
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
const out = [];
const seen = new Set();
const errors = [];
for (const f of files) {
  const list = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
  for (const [i, m] of list.entries()) {
    const where = `${f} #${i + 1}`;
    const text = String(m.text || "").trim();
    if (!text) errors.push(`${where}: empty`);
    if (text.length > 160) errors.push(`${where}: ${text.length} characters`);
    if (/[|\\"\r\n]/.test(text)) errors.push(`${where}: forbidden character`);
    for (const p of text.match(/\{[^}]*\}/g) || []) {
      if (p !== "{name}" && p !== "{what}") errors.push(`${where}: unknown placeholder ${p}`);
    }
    const key = text.toLowerCase();
    if (seen.has(key)) errors.push(`${where}: duplicate`);
    seen.add(key);
    out.push({ tone: String(m.tone || "?"), text, source: f.replace(/\.json$/, "") });
  }
}
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

const lines = [
  "-- Generated by tools/gen_messages.js from tools/messages/*.json. Do not edit by hand.",
  "-- Random mail body messages; {name} is the recipient's first name, {what} what is sent.",
  "local _, ns = ...",
  "ns.MESSAGES = {",
];
for (const m of out) lines.push(`    "${m.text}", -- ${m.tone} (${m.source})`);
lines.push("}");
process.stdout.write(lines.join("\n") + "\n");
