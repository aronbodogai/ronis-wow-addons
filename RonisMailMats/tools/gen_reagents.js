#!/usr/bin/env node
// Generates RonisMailMats/Data/Reagents.lua from RonisItemPedia/Data/Recipes.lua:
// for every profession, the set of item IDs used as a reagent by any recipe.
//
// Usage (from the AddOns folder):
//   node RonisMailMats/tools/gen_reagents.js > RonisMailMats/Data/Reagents.lua
"use strict";
const fs = require("fs");
const path = require("path");

const src = path.join(__dirname, "..", "..", "RonisItemPedia", "Data", "Recipes.lua");
const text = fs.readFileSync(src, "utf8");

const build = (text.match(/ns\.RECIPE_BUILD = "([^"]+)"/) || [])[1] || "?";
const profs = JSON.parse(
  "[" + text.match(/ns\.RECIPE_PROFS = \{([^}]*)\}/)[1] + "]"
);

// Each recipe line: {spellID,profIndex,product,min,max,{reagent,count,...}},
const sets = profs.map(() => new Set());
const re = /^\s*\{(\d+),(\d+),(\d+),(\d+),(\d+),\{([\d,]*)\}\},?\s*$/gm;
let m, n = 0;
while ((m = re.exec(text))) {
  n++;
  const prof = Number(m[2]) - 1;
  const r = m[6].split(",").filter(Boolean).map(Number);
  for (let i = 0; i < r.length; i += 2) sets[prof].add(r[i]);
}
if (n === 0) throw new Error("no recipes parsed from " + src);

const out = [];
out.push("-- GENERATED by tools/gen_reagents.js from RonisItemPedia/Data/Recipes.lua");
out.push(`-- (recipe build ${build}, ${n} recipes). Do not edit by hand.`);
out.push("-- Profession name -> list of item IDs used as reagents by that profession.");
out.push("local _, ns = ...");
out.push("ns.REAGENTS = {");
profs.forEach((name, i) => {
  const ids = [...sets[i]].sort((a, b) => a - b);
  out.push(`  [${JSON.stringify(name)}] = {${ids.join(",")}},`);
});
out.push("}");
process.stdout.write(out.join("\n") + "\n");
