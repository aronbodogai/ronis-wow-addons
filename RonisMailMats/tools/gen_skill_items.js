#!/usr/bin/env node
// Generates RonisMailMats/Data/SkillItems.lua: items that need a non-crafting
// skill to use, from the WoW Forever client's own DB2 tables (CSV exports
// from https://wago.tools/db2/<Table>/csv?build=<build>).
//
//   Comprehension (skill line 3012, mage): scrolls with RequiredSkill 3012.
//   Lockpicking (skill line 633, rogue): items whose Lock needs lock type 1
//   (Lockpicking) - lockboxes, junkboxes, locked chests.
//
// Usage:
//   node tools/gen_skill_items.js <dir-with-csvs> <build> > Data/SkillItems.lua
// Needed tables: ItemSparse, Lock.
"use strict";
const fs = require("fs");
const path = require("path");

const [dir, build] = process.argv.slice(2);
if (!dir || !build) {
  console.error("usage: gen_skill_items.js <csv-dir> <build>");
  process.exit(1);
}

function parseCSV(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else quoted = false;
      } else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field.replace(/\r$/, "")); rows.push(row); row = []; field = ""; }
    else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const head = rows.shift();
  return rows.filter((r) => r.length > 1).map((r) => Object.fromEntries(head.map((k, i) => [k, r[i]])));
}

const read = (t) => parseCSV(fs.readFileSync(path.join(dir, t + ".csv"), "utf8"));
const items = read("ItemSparse");
const locks = new Map(read("Lock").map((l) => [l.ID, l]));

const LOCK_TYPE_ITEM = "2";       // Lock.Type_N: the lock is a LockType ...
const LOCKTYPE_LOCKPICKING = "1"; // ... and LockType 1 is Lockpicking
const SKILL_COMPREHENSION = "3012";

// Test, placeholder and unreachable items still in the client data.
const junk = (it) =>
  /^(Deprecated|\[DNT\]|Test )/i.test(it.Display_lang) ||
  it.ID === "6712"; // Practice Lock: a quest object you cannot mail

const out = { Comprehension: [], Lockpicking: [] };
for (const it of items) {
  if (junk(it) || it.Bonding !== "0") continue; // only items that can be mailed
  if (it.RequiredSkill === SKILL_COMPREHENSION) {
    out.Comprehension.push([+it.ID, +it.RequiredSkillRank, it.Display_lang]);
  }
  const lock = it.LockID !== "0" && locks.get(it.LockID);
  if (lock) {
    for (let k = 0; k < 8; k++) {
      if (lock["Type_" + k] === LOCK_TYPE_ITEM && lock["_Index_" + k] === LOCKTYPE_LOCKPICKING) {
        const skill = +lock["Skill_" + k];
        if (skill <= 300) out.Lockpicking.push([+it.ID, skill, it.Display_lang]);
        break;
      }
    }
  }
}

const lines = [
  "-- Generated by tools/gen_skill_items.js from the client's ItemSparse and Lock",
  `-- tables (build ${build}). Do not edit by hand.`,
  "-- SKILL_ITEMS[skill] = { {itemID, required skill rank}, ... }",
  "local _, ns = ...",
  "ns.SKILL_ITEMS = {",
];
for (const skill of Object.keys(out)) {
  const list = out[skill].sort((a, b) => a[1] - b[1] || a[0] - b[0]);
  lines.push(`    ["${skill}"] = {`);
  for (const [id, rank, name] of list) lines.push(`        {${id}, ${rank}}, -- ${name}`);
  lines.push("    },");
}
lines.push("}");
process.stdout.write(lines.join("\n") + "\n");
