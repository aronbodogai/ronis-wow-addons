#!/usr/bin/env node
// Generates RonisMailMats/Data/ClassReagents.lua: items that class spells use
// up (a shaman's Ankh and Fish Oil, a mage's Arcane Powder and runes...), from
// the WoW Forever client's own DB2 tables (CSV exports from
// https://wago.tools/db2/<Table>/csv?build=<build>).
//
// A spell is a class spell when SkillLineAbility puts it in a class skill line
// (SkillLine.CategoryID 7) for exactly one class. Engraving and rune lines are
// left out (season-of-discovery leftovers), and so are items that bind.
//
// Usage:
//   node tools/gen_class_reagents.js <dir-with-csvs> <build> > Data/ClassReagents.lua
// Needed tables: ItemSparse, SkillLine, SkillLineAbility, SpellReagents.
"use strict";
const fs = require("fs");
const path = require("path");

const [dir, build] = process.argv.slice(2);
if (!dir || !build) {
  console.error("usage: gen_class_reagents.js <csv-dir> <build>");
  process.exit(1);
}

function parseCSV(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else quoted = false;
      } else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n") { row.push(field.replace(/\r$/, "")); rows.push(row); row = []; field = ""; }
    else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const head = rows.shift();
  return rows.filter((r) => r.length > 1).map((r) => Object.fromEntries(head.map((k, i) => [k, r[i]])));
}

const read = (t) => parseCSV(fs.readFileSync(path.join(dir, t + ".csv"), "utf8"));
const items = new Map(read("ItemSparse").map((i) => [i.ID, i]));
const skillLines = new Map(read("SkillLine").map((s) => [s.ID, s]));

const CLASS_CATEGORY = "7";
const SKIP_LINES = new Set(["2851", "2853"]); // Engraving, Runes
const CLASS_BITS = {
  1: "WARRIOR", 2: "PALADIN", 4: "HUNTER", 8: "ROGUE", 16: "PRIEST",
  64: "SHAMAN", 128: "MAGE", 256: "WARLOCK", 1024: "DRUID",
};

const spellClass = new Map();
for (const a of read("SkillLineAbility")) {
  const line = skillLines.get(a.SkillLine);
  if (!line || line.CategoryID !== CLASS_CATEGORY || SKIP_LINES.has(a.SkillLine)) continue;
  const cls = CLASS_BITS[+a.ClassMask];
  if (cls) spellClass.set(a.Spell, cls);
}

const out = {};
for (const r of read("SpellReagents")) {
  const cls = spellClass.get(r.SpellID);
  if (!cls) continue;
  for (let k = 0; k < 8; k++) {
    const id = r["Reagent_" + k];
    const it = id !== "0" && items.get(id);
    if (!it || it.Bonding !== "0" || /^(Deprecated|\[DNT\]|Test )/i.test(it.Display_lang)) continue;
    out[cls] = out[cls] || new Map();
    out[cls].set(+id, it.Display_lang);
  }
}

const lines = [
  "-- Generated by tools/gen_class_reagents.js from the client's SkillLineAbility,",
  `-- SkillLine, SpellReagents and ItemSparse tables (build ${build}). Do not edit by hand.`,
  "-- CLASS_REAGENTS[class token] = { itemID, ... }: items that class's spells use up.",
  "local _, ns = ...",
  "ns.CLASS_REAGENTS = {",
];
for (const cls of Object.keys(out).sort()) {
  lines.push(`    ${cls} = {`);
  for (const [id, name] of [...out[cls]].sort((a, b) => a[0] - b[0])) lines.push(`        ${id}, -- ${name}`);
  lines.push("    },");
}
lines.push("}");
process.stdout.write(lines.join("\n") + "\n");
